import React, { useState, useEffect, useRef } from 'react';
import { motion, AnimatePresence } from 'motion/react';
import {
  ArrowLeft,
  Sparkles,
  Copy,
  Check,
  Wand2,
  Camera,
  ShieldAlert,
  Tag,
  Lightbulb,
  RefreshCw,
  Layers,
  Upload,
  Image as ImageIcon,
  Compass,
  CheckCircle2,
  AlertTriangle,
  ArrowRight,
  ShieldCheck,
  Sliders,
  Maximize2,
  BookOpen,
  Zap
} from 'lucide-react';
import { StockPromptResult, DistinctPromptVariation } from '../types';
import { GoogleAdSenseBanner } from './GoogleAdSenseBanner';

interface PromptStudioDashboardProps {
  onBack: () => void;
  customApiKey?: string;
  showToast: (msg: string) => void;
  initialConcept?: string;
  themeMode?: 'light' | 'dark';
  onSendToStudio?: (title: string, keywords: string[], concept: string) => void;
  onOpenMonetizeHub?: () => void;
}

const TRENDING_INSPIRATIONS = [
  'Sustainable solar energy engineers inspecting panels in futuristic farm',
  'Autumn cozy cinnamon pastries and coffee flat lay on rustic wood table',
  'Diverse multi-generational family cooking together in sunlit modern kitchen',
  'Minimalist ergonomic home office workstation with lush indoor monstera plant',
  'Senior couple practicing yoga outdoors in morning park with soft golden rim light',
  'Electric mobility charging hub in clean European smart architectural city',
];

export const PromptStudioDashboard: React.FC<PromptStudioDashboardProps> = ({
  onBack,
  customApiKey,
  showToast,
  initialConcept,
  themeMode = 'light',
  onSendToStudio,
  onOpenMonetizeHub,
}) => {
  const isLight = themeMode === 'light';
  
  // Input Modes: 'text' = concept description, 'image' = reverse engineer uploaded image
  const [inputMode, setInputMode] = useState<'text' | 'image'>('text');
  const [concept, setConcept] = useState(initialConcept || '');
  const [style, setStyle] = useState('Commercial Stock Photography');
  const [aspectRatio, setAspectRatio] = useState('16:9');
  const [lighting, setLighting] = useState('Clean High-Key Commercial Daylight');
  const [shotType, setShotType] = useState('Medium shot with intentional copy space');
  const [isLoading, setIsLoading] = useState(false);
  const [result, setResult] = useState<StockPromptResult | null>(null);
  const [copiedKey, setCopiedKey] = useState<string | null>(null);
  const [activeModelTab, setActiveModelTab] = useState<{ [variationId: string]: 'nano' | 'chatgpt' | 'midjourney' | 'firefly' | 'flux' }>({});
  const [selectedVariationIndex, setSelectedVariationIndex] = useState<number>(0);
  const [showGuidelinesModal, setShowGuidelinesModal] = useState<boolean>(false);
  const [enforceDeepDetails, setEnforceDeepDetails] = useState<boolean>(true);
  const [userEditedPrompts, setUserEditedPrompts] = useState<{ [key: string]: string }>({});
  const [showVisualSim, setShowVisualSim] = useState<{ [variationId: string]: boolean }>({});

  const handleAutoEnrichConcept = () => {
    const raw = concept.trim();
    if (!raw) {
      showToast('Please type a base concept first (e.g. "green tea leaves", "luxury watch").');
      return;
    }
    const enriched = `${raw}, photographed on Hasselblad H6D-100c medium format camera with Zeiss Otus 35mm f/2.8 prime lens, 3-point diffused softbox lighting with warm golden rim illumination, pristine physical micro-textures, generous negative copy space on left for typography, calibrated sRGB natural color grading, raw photorealistic 8k commercial stock photography`;
    setConcept(enriched);
    showToast('✓ Auto-enriched concept with medium-format optics, lighting geometry, and negative copy space!');
  };

  // Image Upload State for Vision Image-to-Prompt
  const [uploadedImageBase64, setUploadedImageBase64] = useState<string | null>(null);
  const [uploadedImageMime, setUploadedImageMime] = useState<string>('image/jpeg');
  const [uploadedImageName, setUploadedImageName] = useState<string>('');
  const fileInputRef = useRef<HTMLInputElement>(null);
  const hasAutoGeneratedRef = useRef(false);

  useEffect(() => {
    if (initialConcept && initialConcept.trim() && !hasAutoGeneratedRef.current) {
      hasAutoGeneratedRef.current = true;
      setConcept(initialConcept.trim());
      handleGenerate(initialConcept.trim());
    }
  }, [initialConcept]);

  const handleImageFileChange = (e: React.ChangeEvent<HTMLInputElement>) => {
    const file = e.target.files?.[0];
    if (!file) return;

    if (!file.type.startsWith('image/')) {
      showToast('Please select a valid image file (JPG, PNG, WebP).');
      return;
    }

    setUploadedImageName(file.name);
    setUploadedImageMime(file.type || 'image/jpeg');

    const reader = new FileReader();
    reader.onload = (event) => {
      const dataUrl = event.target?.result as string;
      setUploadedImageBase64(dataUrl);
    };
    reader.readAsDataURL(file);
  };

  const handleGenerateFromImage = async () => {
    if (!uploadedImageBase64) {
      showToast('Please upload an image first.');
      return;
    }

    setIsLoading(true);
    try {
      const headers: Record<string, string> = {
        'Content-Type': 'application/json',
      };
      if (customApiKey) {
        headers['x-api-key'] = customApiKey;
      }

      const res = await fetch('/api/reverse-image-prompt', {
        method: 'POST',
        headers,
        body: JSON.stringify({
          imageBase64: uploadedImageBase64,
          mimeType: uploadedImageMime,
          fileName: uploadedImageName,
        }),
      });

      if (!res.ok) {
        const errorData = await res.json().catch(() => ({}));
        throw new Error(errorData.error || 'Failed to analyze image for prompts');
      }

      const data = await res.json();
      setResult({
        concept: uploadedImageName.replace(/\.[^/.]+$/, '').replace(/[-_]+/g, ' '),
        midjourneyPrompt: data.midjourneyPrompt,
        fireflyPrompt: data.fireflyPrompt,
        fluxPrompt: data.fluxPrompt,
        negativePrompt: data.negativePrompt,
        commercialTips: data.commercialReplicationTips || data.styleBreakdown,
        suggestedTitle: data.distinctVariations?.[0]?.distinctTitle || `Commercial Visual of ${uploadedImageName.replace(/\.[^/.]+$/, '')}`,
        suggestedKeywords: data.distinctVariations?.[0]?.distinctKeywords || ['commercial photography', 'high quality', 'stock visual'],
        distinctVariations: data.distinctVariations,
        similarityDefenseSummary: "Engineered 5 fundamentally distinct commercial angles from this image to 100% comply with Adobe Stock's June 11, 2026 Distinct Content Guidelines."
      });

      setSelectedVariationIndex(0);
      showToast('✓ Deconstructed visual into 5 distinct non-similar stock prompts!');
    } catch (err: any) {
      console.error(err);
      showToast(err.message || 'Error analyzing image. Please try again.');
    } finally {
      setIsLoading(false);
    }
  };

  const handleGenerate = async (conceptToUse?: string) => {
    const finalConcept = (conceptToUse || concept).trim();
    if (!finalConcept) {
      showToast('Please type a photo concept or select an inspiration.');
      return;
    }

    setIsLoading(true);
    try {
      const headers: Record<string, string> = {
        'Content-Type': 'application/json',
      };
      if (customApiKey) {
        headers['x-api-key'] = customApiKey;
      }

      const res = await fetch('/api/generate-stock-prompt', {
        method: 'POST',
        headers,
        body: JSON.stringify({
          concept: finalConcept,
          style,
          aspectRatio,
          lighting,
          shotType,
          enforceDeepDetails,
        }),
      });

      if (!res.ok) {
        const errorData = await res.json().catch(() => ({}));
        throw new Error(errorData.error || 'Failed to generate prompts');
      }

      const data: StockPromptResult = await res.json();
      setResult(data);
      setSelectedVariationIndex(0);
      showToast('✓ Generated 5 Distinct Anti-Similarity Stock Prompts!');
    } catch (err: any) {
      console.error(err);
      showToast(err.message || 'Error generating prompts. Check API key in settings.');
    } finally {
      setIsLoading(false);
    }
  };

  const copyText = (text: string, keyName: string) => {
    navigator.clipboard.writeText(text);
    setCopiedKey(keyName);
    showToast(`✓ Copied ${keyName} to clipboard!`);
    setTimeout(() => setCopiedKey(null), 2000);
  };

  return (
    <motion.div
      initial={{ opacity: 0, y: 10 }}
      animate={{ opacity: 1, y: 0 }}
      exit={{ opacity: 0, y: -10 }}
      className="space-y-8 pb-16"
    >
      {/* Top Architectural Header */}
      <div className={`flex flex-col md:flex-row items-start md:items-center justify-between gap-6 p-7 sm:p-10 rounded-[32px] transition-colors sovereign-prism-card ${
        isLight
          ? 'crystal-architectural-slab-light text-neutral-900'
          : 'crystal-architectural-slab-dark text-white'
      }`}>
        <div className="flex items-center gap-4">
          <button
            onClick={onBack}
            className={`p-3 rounded-2xl border transition cursor-pointer shrink-0 ${
              isLight
                ? 'bg-[#fbfaf8] hover:bg-neutral-100 border-neutral-200 text-neutral-700'
                : 'bg-neutral-900 hover:bg-neutral-800 border-neutral-800 text-neutral-300'
            }`}
            title="Back to Studio Workspace"
          >
            <ArrowLeft className="w-4 h-4" />
          </button>
          <div className="space-y-1">
            <div className="flex items-center gap-2 text-[10.5px] font-mono uppercase tracking-[0.2em] text-neutral-400">
              <span>03 · PROMPT ATELIER</span>
              <span>·</span>
              <span className="text-emerald-500 font-bold flex items-center gap-1">
                <ShieldCheck className="w-3.5 h-3.5" />
                ADOBE STOCK SIMILAR CONTENT SHIELD
              </span>
            </div>
            <h1 className="text-xl sm:text-3xl font-bold tracking-[-0.025em] flex items-center gap-2.5">
              <span>
                Distinct{' '}
                <span className="font-editorial italic font-semibold text-[1.08em] luxury-headline-gradient pr-1">
                  Prompt Engineering
                </span>{' '}
                Atelier
              </span>
            </h1>
            <p className={`text-xs sm:text-sm ${isLight ? 'text-neutral-500' : 'text-neutral-400'}`}>
              Generates 100% unique, commercial prompts for <strong>Nano Banana Pro</strong>, <strong>ChatGPT / DALL-E</strong>, Midjourney &amp; Firefly that pass Adobe Stock's June 11, 2026 Distinct Content rules.
            </p>
          </div>
        </div>

        <div className="flex items-center gap-2.5 shrink-0">
          <button
            type="button"
            onClick={() => setShowGuidelinesModal(true)}
            className={`px-3.5 py-2 rounded-xl text-xs font-semibold border flex items-center gap-1.5 transition cursor-pointer ${
              isLight
                ? 'bg-[#fbfaf8] hover:bg-neutral-100 border-neutral-200 text-neutral-800'
                : 'bg-white/5 hover:bg-white/10 border-white/15 text-neutral-200'
            }`}
          >
            <BookOpen className="w-3.5 h-3.5 text-amber-500" />
            <span>Adobe Stock Similarity Rules</span>
          </button>
        </div>
      </div>

      {/* Official High-Yield Google Monetized Leaderboard Unit */}
      <GoogleAdSenseBanner
        format="leaderboard"
        themeMode={themeMode}
        onOpenMonetizeHub={onOpenMonetizeHub}
      />

      {/* Adobe Stock Similar Content Prevention Banner */}
      <div className={`p-4 sm:p-5 rounded-2xl border flex flex-col sm:flex-row items-start sm:items-center justify-between gap-4 ${
        isLight
          ? 'bg-amber-50/70 border-amber-200/90 text-amber-950'
          : 'bg-amber-500/10 border-amber-500/20 text-amber-200'
      }`}>
        <div className="flex items-start gap-3">
          <div className="p-2 rounded-xl bg-amber-500/20 text-amber-600 dark:text-amber-400 shrink-0 mt-0.5">
            <ShieldAlert className="w-4 h-4" />
          </div>
          <div className="space-y-0.5">
            <div className="text-xs font-bold flex items-center gap-2">
              <span>Why Adobe Stock Rejects Similar Content &amp; How This Atelier Protects You:</span>
              <span className="text-[10px] font-mono uppercase px-2 py-0.5 rounded-full bg-amber-500/20 font-semibold">
                Updated Jun 11, 2026 Policy
              </span>
            </div>
            <p className="text-[11px] opacity-90 leading-relaxed max-w-4xl">
              Adobe Stock reviewers refuse sequential shots, slight angle variations, and images tagged with identical titles or metadata. This Atelier automatically engineers <strong>5 fundamentally distinct conceptual archetypes</strong> (Wide Hero, Macro Texture, Overhead Flat Lay, Candid Motion, Minimalist Metaphor) so each asset serves a different customer need with 0% similarity rejection risk.
            </p>
          </div>
        </div>
      </div>

      {/* Dual Input Mode Selector Tabs */}
      <div className="flex items-center gap-2">
        <button
          type="button"
          onClick={() => setInputMode('text')}
          className={`px-4 py-2 rounded-xl text-xs font-bold transition flex items-center gap-2 border cursor-pointer ${
            inputMode === 'text'
              ? (isLight ? 'bg-neutral-950 text-white border-neutral-950 shadow-sm' : 'bg-white text-neutral-950 border-white')
              : (isLight ? 'bg-white text-neutral-600 border-neutral-200 hover:border-neutral-400' : 'bg-neutral-900 text-neutral-300 border-neutral-800 hover:border-neutral-700')
          }`}
        >
          <Sparkles className="w-3.5 h-3.5 text-amber-500" />
          <span>Idea or Concept Description</span>
        </button>

        <button
          type="button"
          onClick={() => setInputMode('image')}
          className={`px-4 py-2 rounded-xl text-xs font-bold transition flex items-center gap-2 border cursor-pointer ${
            inputMode === 'image'
              ? (isLight ? 'bg-neutral-950 text-white border-neutral-950 shadow-sm' : 'bg-white text-neutral-950 border-white')
              : (isLight ? 'bg-white text-neutral-600 border-neutral-200 hover:border-neutral-400' : 'bg-neutral-900 text-neutral-300 border-neutral-800 hover:border-neutral-700')
          }`}
        >
          <ImageIcon className="w-3.5 h-3.5 text-cyan-400" />
          <span>Upload Reference Image (Vision Deconstruction)</span>
        </button>
      </div>

      {/* INPUT CONTAINER 1: TEXT CONCEPT */}
      {inputMode === 'text' && (
        <div className={`p-7 sm:p-9 rounded-[32px] space-y-6 sovereign-prism-card ${
          isLight
            ? 'crystal-architectural-slab-light text-neutral-900'
            : 'crystal-architectural-slab-dark text-white'
        }`}>
          <div>
            <label className="text-[11px] font-mono font-bold uppercase tracking-[0.14em] text-neutral-400 block mb-2">
              Commercial Photo Concept / Shoot Description
            </label>
            <div className="flex flex-col sm:flex-row gap-2.5">
              <input
                type="text"
                value={concept}
                onChange={(e) => setConcept(e.target.value)}
                onKeyDown={(e) => e.key === 'Enter' && handleGenerate()}
                placeholder="e.g. Traditional tea garden artisan picking fresh organic green tea leaves in Sylhet hills with copy space..."
                className={`flex-1 border rounded-xl px-4 py-3 text-sm focus:outline-none transition ${
                  isLight
                    ? 'bg-[#fbfaf8] border-neutral-200/90 text-neutral-900 placeholder-neutral-400 focus:bg-white focus:border-neutral-900'
                    : 'bg-neutral-950 border-neutral-800 text-white placeholder-neutral-500 focus:border-neutral-600'
                }`}
              />
              <button
                onClick={() => handleGenerate()}
                disabled={isLoading || !concept.trim()}
                className={`font-bold text-xs sm:text-sm px-6 py-3 rounded-xl transition flex items-center justify-center gap-2 cursor-pointer disabled:opacity-40 ${
                  isLight
                    ? 'bg-neutral-950 hover:bg-black text-white'
                    : 'bg-white hover:bg-neutral-200 text-neutral-950'
                }`}
              >
                {isLoading ? (
                  <>
                    <RefreshCw className="w-4 h-4 animate-spin" /> Synthesizing Distinct Prompts...
                  </>
                ) : (
                  <>
                    <Sparkles className="w-4 h-4 text-amber-500" /> Generate 5 Distinct Prompts
                  </>
                )}
              </button>
            </div>

            <div className="flex flex-wrap items-center justify-between gap-3 pt-2">
              <button
                type="button"
                onClick={handleAutoEnrichConcept}
                className={`text-xs px-3 py-1.5 rounded-xl border font-semibold flex items-center gap-1.5 cursor-pointer transition ${
                  isLight
                    ? 'bg-amber-50 hover:bg-amber-100 border-amber-200 text-amber-900'
                    : 'bg-amber-500/10 hover:bg-amber-500/20 border-amber-500/30 text-amber-300'
                }`}
                title="Automatically expand your idea with medium-format optics, lighting geometry, and negative copy space"
              >
                <Wand2 className="w-3.5 h-3.5 text-amber-500" />
                <span>Auto-Enrich Concept (+Optics &amp; Lighting Blueprint)</span>
              </button>

              <label className="flex items-center gap-2 cursor-pointer text-xs font-semibold select-none">
                <input
                  type="checkbox"
                  checked={enforceDeepDetails}
                  onChange={(e) => setEnforceDeepDetails(e.target.checked)}
                  className="rounded accent-emerald-500 w-4 h-4 cursor-pointer"
                />
                <span className={enforceDeepDetails ? 'text-emerald-600 dark:text-emerald-400 font-bold' : 'text-neutral-400'}>
                  Enforce Deep Master Commercial Blueprint (120–180 Words)
                </span>
              </label>
            </div>
          </div>

          {/* Quick Inspiration Pills */}
          <div className="space-y-2">
            <span className="text-[11px] font-semibold text-neutral-400 flex items-center gap-1.5">
              <Lightbulb className="w-3.5 h-3.5 text-amber-500" /> High-Converting Commercial Inspirations:
            </span>
            <div className="flex flex-wrap gap-2">
              {TRENDING_INSPIRATIONS.map((insp, idx) => (
                <button
                  key={idx}
                  onClick={() => {
                    setConcept(insp);
                    handleGenerate(insp);
                  }}
                  className={`text-xs border px-3 py-1.5 rounded-xl transition text-left cursor-pointer ${
                    isLight
                      ? 'bg-[#fbfaf8] hover:bg-neutral-100 border-neutral-200/90 text-neutral-700 hover:border-neutral-900'
                      : 'bg-neutral-900 hover:bg-neutral-800 border-neutral-800 text-neutral-300'
                  }`}
                >
                  {insp}
                </button>
              ))}
            </div>
          </div>

          {/* Options Grid */}
          <div className={`grid grid-cols-1 sm:grid-cols-2 md:grid-cols-4 gap-3 pt-4 border-t ${
            isLight ? 'border-neutral-100' : 'border-neutral-800/80'
          }`}>
            <div>
              <label className="text-[10px] font-mono uppercase tracking-[0.14em] text-neutral-400 block mb-1.5">
                Target Style
              </label>
              <select
                value={style}
                onChange={(e) => setStyle(e.target.value)}
                className={`w-full border text-xs rounded-xl p-2.5 font-medium focus:outline-none ${
                  isLight
                    ? 'bg-[#fbfaf8] border-neutral-200 text-neutral-900'
                    : 'bg-neutral-900 border-neutral-800 text-neutral-200'
                }`}
              >
                <option value="Commercial Stock Photography">Commercial Stock Photography</option>
                <option value="Authentic Candid Lifestyle">Authentic Candid Lifestyle</option>
                <option value="3D Isometric Render">3D Isometric Render</option>
                <option value="Minimal Flat Vector Illustration">Minimal Flat Vector</option>
                <option value="Editorial Photojournalism">Editorial Photojournalism</option>
              </select>
            </div>

            <div>
              <label className="text-[10px] font-mono uppercase tracking-[0.14em] text-neutral-400 block mb-1.5">
                Aspect Ratio
              </label>
              <select
                value={aspectRatio}
                onChange={(e) => setAspectRatio(e.target.value)}
                className={`w-full border text-xs rounded-xl p-2.5 font-medium focus:outline-none ${
                  isLight
                    ? 'bg-[#fbfaf8] border-neutral-200 text-neutral-900'
                    : 'bg-neutral-900 border-neutral-800 text-neutral-200'
                }`}
              >
                <option value="16:9">16:9 (Landscape / Banner)</option>
                <option value="3:2">3:2 (Classic DSLR Frame)</option>
                <option value="4:5">4:5 (Social &amp; Mobile Vertical)</option>
                <option value="1:1">1:1 (Square Editorial)</option>
              </select>
            </div>

            <div>
              <label className="text-[10px] font-mono uppercase tracking-[0.14em] text-neutral-400 block mb-1.5">
                Commercial Lighting
              </label>
              <select
                value={lighting}
                onChange={(e) => setLighting(e.target.value)}
                className={`w-full border text-xs rounded-xl p-2.5 font-medium focus:outline-none ${
                  isLight
                    ? 'bg-[#fbfaf8] border-neutral-200 text-neutral-900'
                    : 'bg-neutral-900 border-neutral-800 text-neutral-200'
                }`}
              >
                <option value="Clean High-Key Commercial Daylight">High-Key Daylight</option>
                <option value="Warm Golden Hour Sunlight">Golden Hour Glow</option>
                <option value="Softbox Studio Commercial Rim Light">Studio Softbox</option>
                <option value="Moody Cinematic Window Shadows">Moody Natural Shadows</option>
              </select>
            </div>

            <div>
              <label className="text-[10px] font-mono uppercase tracking-[0.14em] text-neutral-400 block mb-1.5">
                Composition / Framing
              </label>
              <select
                value={shotType}
                onChange={(e) => setShotType(e.target.value)}
                className={`w-full border text-xs rounded-xl p-2.5 font-medium focus:outline-none ${
                  isLight
                    ? 'bg-[#fbfaf8] border-neutral-200 text-neutral-900'
                    : 'bg-neutral-900 border-neutral-800 text-neutral-200'
                }`}
              >
                <option value="Medium shot with intentional copy space">Medium Shot + Copy Space</option>
                <option value="Wide panoramic establishing angle">Wide Panoramic View</option>
                <option value="Close-up macro detail with blurred background">Macro Detail (f/1.8)</option>
                <option value="Top-down flat lay with negative space">Top-Down Flat Lay</option>
              </select>
            </div>
          </div>
        </div>
      )}

      {/* INPUT CONTAINER 2: REFERENCE IMAGE UPLOAD */}
      {inputMode === 'image' && (
        <div className={`p-7 sm:p-9 rounded-[32px] space-y-6 sovereign-prism-card ${
          isLight
            ? 'crystal-architectural-slab-light text-neutral-900'
            : 'crystal-architectural-slab-dark text-white'
        }`}>
          <div>
            <label className="text-[11px] font-mono font-bold uppercase tracking-[0.14em] text-neutral-400 block mb-2">
              Upload Reference Photo or Concept Image
            </label>
            <p className={`text-xs ${isLight ? 'text-neutral-500' : 'text-neutral-400'} mb-4`}>
              Our vision engine deconstructs the subject, lighting, and composition of your image and generates 5 completely distinct prompt variations so you never trigger Adobe Stock's "Similar Content" refusal!
            </p>

            <input
              type="file"
              ref={fileInputRef}
              accept="image/jpeg,image/png,image/webp"
              onChange={handleImageFileChange}
              className="hidden"
            />

            {!uploadedImageBase64 ? (
              <div
                onClick={() => fileInputRef.current?.click()}
                className={`border-2 border-dashed rounded-2xl p-8 sm:p-12 text-center cursor-pointer transition flex flex-col items-center justify-center gap-3 ${
                  isLight
                    ? 'border-neutral-300 hover:border-neutral-600 bg-neutral-50/50 hover:bg-neutral-50'
                    : 'border-neutral-800 hover:border-neutral-600 bg-neutral-950/50 hover:bg-neutral-950'
                }`}
              >
                <div className="w-12 h-12 rounded-2xl bg-cyan-500/10 border border-cyan-500/20 flex items-center justify-center text-cyan-400">
                  <Upload className="w-6 h-6" />
                </div>
                <div>
                  <div className="text-sm font-bold">Click or drag &amp; drop reference photo here</div>
                  <div className="text-xs text-neutral-400 mt-1">Supports JPG, PNG, WebP (Up to 25MB)</div>
                </div>
              </div>
            ) : (
              <div className="flex flex-col sm:flex-row items-center gap-5 p-4 rounded-2xl border border-neutral-200 dark:border-neutral-800 bg-neutral-50 dark:bg-neutral-950">
                <img
                  src={uploadedImageBase64}
                  alt="Reference uploaded"
                  className="w-28 h-28 object-cover rounded-xl border border-neutral-200 dark:border-neutral-800 shrink-0"
                />
                <div className="space-y-2 flex-1 min-w-0">
                  <div className="flex items-center gap-2">
                    <span className="text-xs font-bold truncate">{uploadedImageName || 'Reference Image'}</span>
                    <span className="text-[10px] font-mono px-2 py-0.5 rounded bg-emerald-500/15 text-emerald-600 dark:text-emerald-400 border border-emerald-500/30">
                      Visual Loaded
                    </span>
                  </div>
                  <p className="text-xs text-neutral-400">
                    Ready to reverse-engineer into 5 non-similar commercial prompt archetypes.
                  </p>
                  <div className="flex items-center gap-2 pt-1">
                    <button
                      type="button"
                      onClick={handleGenerateFromImage}
                      disabled={isLoading}
                      className="px-4 py-2 rounded-xl text-xs font-bold bg-neutral-950 hover:bg-black text-white dark:bg-white dark:text-neutral-950 dark:hover:bg-neutral-200 transition flex items-center gap-1.5 cursor-pointer disabled:opacity-40"
                    >
                      {isLoading ? (
                        <>
                          <RefreshCw className="w-3.5 h-3.5 animate-spin" /> Deconstructing Image...
                        </>
                      ) : (
                        <>
                          <Wand2 className="w-3.5 h-3.5 text-amber-500" /> Generate 5 Distinct Prompts
                        </>
                      )}
                    </button>
                    <button
                      type="button"
                      onClick={() => {
                        setUploadedImageBase64(null);
                        setUploadedImageName('');
                      }}
                      className="px-3 py-2 rounded-xl text-xs font-semibold text-neutral-500 hover:text-neutral-700 dark:hover:text-neutral-300 cursor-pointer"
                    >
                      Remove
                    </button>
                  </div>
                </div>
              </div>
            )}
          </div>
        </div>
      )}

      {/* RESULTS SECTION: 5 DISTINCT COMMERCIAL ARCHETYPES */}
      {result && result.distinctVariations && result.distinctVariations.length > 0 && (
        <div className="space-y-6">
          <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4">
            <div>
              <div className="text-[10.5px] font-mono uppercase tracking-[0.2em] text-neutral-400 mb-1">
                ADOBE STOCK COMPLIANCE VERIFIED
              </div>
              <h3 className={`text-xl font-bold flex items-center gap-2.5 ${isLight ? 'text-neutral-900' : 'text-white'}`}>
                <ShieldCheck className="w-5 h-5 text-emerald-500" />
                <span>5 Distinct Variation Archetypes (0% Similarity Rejection Risk)</span>
              </h3>
              <p className={`text-xs ${isLight ? 'text-neutral-500' : 'text-neutral-400'} mt-1`}>
                Each variation features a fundamentally different composition, camera perspective, and customer search intent.
              </p>
            </div>

            <div className="flex items-center gap-2">
              <span className="text-xs font-mono text-emerald-600 dark:text-emerald-400 font-bold px-3 py-1.5 rounded-xl border border-emerald-500/30 bg-emerald-500/10 flex items-center gap-1.5">
                <CheckCircle2 className="w-3.5 h-3.5" />
                100% Non-Similar Guaranteed
              </span>
            </div>
          </div>

          {/* Archetype Selector Tabs */}
          <div className="grid grid-cols-2 sm:grid-cols-3 lg:grid-cols-5 gap-2.5">
            {result.distinctVariations.map((v, idx) => {
              const isSelected = selectedVariationIndex === idx;
              return (
                <button
                  key={v.id}
                  onClick={() => setSelectedVariationIndex(idx)}
                  className={`p-3.5 rounded-2xl border text-left transition flex flex-col justify-between gap-2 cursor-pointer ${
                    isSelected
                      ? (isLight ? 'bg-neutral-950 text-white border-neutral-950 shadow-md ring-2 ring-neutral-950' : 'bg-white text-neutral-950 border-white shadow-xl ring-2 ring-white')
                      : (isLight ? 'bg-white hover:bg-neutral-50 border-neutral-200 text-neutral-800' : 'bg-[#0f1118] hover:bg-neutral-900 border-neutral-800 text-neutral-300')
                  }`}
                >
                  <div className="flex items-center justify-between text-[10px] font-mono uppercase tracking-wider opacity-70">
                    <span>Variation #{idx + 1}</span>
                    <span>{isSelected ? 'ACTIVE' : '0% SIM'}</span>
                  </div>
                  <div className="text-xs font-bold line-clamp-2">
                    {v.archetype}
                  </div>
                  <div className="text-[10px] font-mono opacity-60 truncate">
                    {v.compositionTag}
                  </div>
                </button>
              );
            })}
          </div>

          {/* ACTIVE VARIATION DETAIL CARD */}
          {(() => {
            const activeVar = result.distinctVariations[selectedVariationIndex] || result.distinctVariations[0];
            const currentModel = activeModelTab[activeVar.id] || 'nano';

            const basePromptText =
              currentModel === 'nano' ? activeVar.nanoBananaPrompt :
              currentModel === 'chatgpt' ? activeVar.chatGptPrompt :
              currentModel === 'midjourney' ? activeVar.midjourneyPrompt :
              currentModel === 'firefly' ? activeVar.fireflyPrompt :
              activeVar.fluxPrompt;

            const promptKey = `${activeVar.id}-${currentModel}`;
            const activePromptText = userEditedPrompts[promptKey] !== undefined ? userEditedPrompts[promptKey] : basePromptText;
            const wordCount = activePromptText.trim().split(/\s+/).filter(Boolean).length;

            return (
              <div className={`p-6 sm:p-8 rounded-[32px] border space-y-6 sovereign-prism-card ${
                isLight ? 'crystal-architectural-slab-light text-neutral-900' : 'crystal-architectural-slab-dark text-white'
              }`}>
                {/* Header Row */}
                <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 pb-4 border-b border-neutral-200/80 dark:border-white/10">
                  <div className="space-y-1">
                    <div className="flex items-center gap-2">
                      <span className="text-[10.5px] font-mono uppercase tracking-wider text-emerald-600 dark:text-emerald-400 font-bold px-2.5 py-0.5 rounded-full bg-emerald-500/15 border border-emerald-500/30">
                        {activeVar.compositionTag}
                      </span>
                      <span className="text-xs text-neutral-400 font-mono">
                        {activeVar.cameraSpecs}
                      </span>
                    </div>
                    <h4 className="text-lg font-bold tracking-tight">
                      {activeVar.archetype}
                    </h4>
                    <p className="text-xs text-neutral-500 dark:text-neutral-400">
                      <strong>Target Customer Need:</strong> {activeVar.customerUseCase}
                    </p>
                  </div>

                  {onSendToStudio && (
                    <button
                      type="button"
                      onClick={() => {
                        onSendToStudio(
                          activeVar.distinctTitle,
                          activeVar.distinctKeywords,
                          activeVar.archetype
                        );
                        showToast(`✓ Staged "${activeVar.archetype}" into Studio Workbench!`);
                      }}
                      className="px-4 py-2 rounded-xl text-xs font-bold bg-emerald-600 hover:bg-emerald-500 text-white flex items-center gap-1.5 transition cursor-pointer shrink-0 shadow-sm"
                    >
                      <ArrowRight className="w-3.5 h-3.5" />
                      <span>Send to Metadata Studio</span>
                    </button>
                  )}
                </div>

                {/* Generator Model Tabs */}
                <div className="space-y-3">
                  <div className="flex items-center justify-between">
                    <label className="text-xs font-mono font-bold uppercase tracking-wider text-neutral-400">
                      Select Generator Model Prompt:
                    </label>
                    <span className="text-[11px] text-neutral-400 font-mono">
                      Calibrated for commercial review
                    </span>
                  </div>

                  <div className="flex flex-wrap items-center gap-2">
                    {[
                      { id: 'nano', label: 'Nano Banana Pro', tag: 'High Commercial' },
                      { id: 'chatgpt', label: 'ChatGPT / DALL-E', tag: 'Photorealistic' },
                      { id: 'midjourney', label: 'Midjourney v6.1', tag: '--v 6.1 raw' },
                      { id: 'firefly', label: 'Adobe Firefly 3', tag: 'Stock Native' },
                      { id: 'flux', label: 'Flux.1 / SDXL', tag: 'Raw Lens' },
                    ].map((m) => {
                      const isActive = currentModel === m.id;
                      return (
                        <button
                          key={m.id}
                          type="button"
                          onClick={() => setActiveModelTab({ ...activeModelTab, [activeVar.id]: m.id as any })}
                          className={`px-3.5 py-1.5 rounded-xl text-xs font-semibold border transition flex items-center gap-1.5 cursor-pointer ${
                            isActive
                              ? (isLight ? 'bg-neutral-950 text-white border-neutral-950 font-bold' : 'bg-white text-neutral-950 border-white font-bold')
                              : (isLight ? 'bg-neutral-50 hover:bg-neutral-100 border-neutral-200 text-neutral-700' : 'bg-neutral-900 hover:bg-neutral-800 border-neutral-800 text-neutral-300')
                          }`}
                        >
                          <span>{m.label}</span>
                          <span className="text-[9.5px] opacity-60 font-mono">({m.tag})</span>
                        </button>
                      );
                    })}
                  </div>

                  {/* Prompt Text Box */}
                  <div className={`p-4 sm:p-5 rounded-2xl border space-y-3 ${
                    isLight ? 'bg-white border-neutral-200/90' : 'bg-neutral-950 border-neutral-800'
                  }`}>
                    <div className="flex flex-wrap items-center justify-between gap-2">
                      <div className="flex items-center gap-2">
                        <span className="text-xs font-bold font-mono text-neutral-400 uppercase">
                          {currentModel.toUpperCase()} PROMPT:
                        </span>
                        <span className="px-2.5 py-0.5 rounded-full text-[10.5px] font-mono font-bold bg-emerald-500/10 text-emerald-600 dark:text-emerald-400 border border-emerald-500/25">
                          {wordCount} Words · Deep Commercial Grade
                        </span>
                      </div>
                      <div className="flex items-center gap-2">
                        <button
                          type="button"
                          onClick={() => {
                            const opticsSnippet = `, shot on Hasselblad H6D-100c medium format camera with Zeiss Otus 35mm f/2.8 prime lens, 3-point soft commercial daylight with 120cm octabox at 45 degrees, subtle warm golden rim illumination, pristine physical micro-textures, generous negative copy space on left for typography, Hasselblad Natural Colour Solution, 8k resolution`;
                            const newText = activePromptText + opticsSnippet;
                            setUserEditedPrompts({ ...userEditedPrompts, [promptKey]: newText });
                            showToast('✓ Appended Hasselblad optics & lighting geometry!');
                          }}
                          className={`text-xs px-2.5 py-1.5 rounded-xl border font-semibold flex items-center gap-1 cursor-pointer transition ${
                            isLight ? 'bg-neutral-100 hover:bg-neutral-200 border-neutral-300 text-neutral-800' : 'bg-neutral-900 hover:bg-neutral-800 border-neutral-700 text-neutral-200'
                          }`}
                          title="Append camera body, prime lens, lighting geometry, and negative copy space"
                        >
                          <Camera className="w-3.5 h-3.5 text-amber-500" />
                          <span>+ Optics &amp; Lighting</span>
                        </button>
                        <button
                          type="button"
                          onClick={() => copyText(activePromptText, `${currentModel.toUpperCase()} Prompt`)}
                          className={`text-xs px-3 py-1.5 rounded-xl border font-bold transition flex items-center gap-1.5 cursor-pointer ${
                            isLight ? 'bg-neutral-950 hover:bg-black text-white' : 'bg-white hover:bg-neutral-200 text-neutral-950'
                          }`}
                        >
                          {copiedKey === `${currentModel.toUpperCase()} Prompt` ? <Check className="w-3.5 h-3.5 text-emerald-500" /> : <Copy className="w-3.5 h-3.5" />}
                          <span>{copiedKey === `${currentModel.toUpperCase()} Prompt` ? 'Copied!' : 'Copy Prompt'}</span>
                        </button>
                      </div>
                    </div>

                    <textarea
                      value={activePromptText}
                      onChange={(e) => setUserEditedPrompts({ ...userEditedPrompts, [promptKey]: e.target.value })}
                      rows={5}
                      className={`w-full text-xs sm:text-sm font-mono leading-relaxed p-3.5 rounded-xl border focus:outline-none transition resize-y select-text ${
                        isLight
                          ? 'bg-[#fbfaf8] border-neutral-200 text-neutral-900 focus:bg-white focus:border-neutral-950'
                          : 'bg-neutral-900 border-neutral-800 text-white focus:border-neutral-600'
                      }`}
                      placeholder="Commercial stock prompt..."
                    />

                    <div className="flex flex-wrap items-center justify-between text-[11px] text-neutral-400 font-mono pt-0.5">
                      <span className="flex items-center gap-1 text-emerald-600 dark:text-emerald-400">
                        <CheckCircle2 className="w-3 h-3" />
                        <span>Exhaustive prompt guarantees zero AI distortions &amp; maximum acceptance</span>
                      </span>
                      {userEditedPrompts[promptKey] && (
                        <button
                          type="button"
                          onClick={() => {
                            const next = { ...userEditedPrompts };
                            delete next[promptKey];
                            setUserEditedPrompts(next);
                            showToast('Reset to original AI synthesis.');
                          }}
                          className="text-amber-500 hover:underline cursor-pointer"
                        >
                          Reset to AI Original
                        </button>
                      )}
                    </div>
                  </div>
                </div>

                {/* Distinct Title & Keywords (Prevents Adobe Stock Metadata Patterns Refusal) */}
                <div className="grid grid-cols-1 md:grid-cols-2 gap-4 pt-2">
                  <div className={`p-4 rounded-2xl border space-y-2 ${
                    isLight ? 'bg-white border-neutral-200/90' : 'bg-neutral-950 border-neutral-800'
                  }`}>
                    <div className="flex items-center justify-between">
                      <span className="text-xs font-bold text-neutral-900 dark:text-white flex items-center gap-1.5">
                        <Tag className="w-3.5 h-3.5 text-amber-500" /> Distinct Stock Title
                      </span>
                      <button
                        type="button"
                        onClick={() => copyText(activeVar.distinctTitle, 'Title')}
                        className="text-xs font-mono text-amber-600 dark:text-amber-400 hover:underline cursor-pointer"
                      >
                        Copy
                      </button>
                    </div>
                    <div className="text-xs font-bold">
                      {activeVar.distinctTitle}
                    </div>
                    <p className="text-[10px] text-neutral-400 font-mono">
                      {activeVar.distinctTitle.length} characters (100% Subject-First, Under 68c)
                    </p>
                  </div>

                  <div className={`p-4 rounded-2xl border space-y-2 ${
                    isLight ? 'bg-white border-neutral-200/90' : 'bg-neutral-950 border-neutral-800'
                  }`}>
                    <div className="flex items-center justify-between">
                      <span className="text-xs font-bold text-neutral-900 dark:text-white flex items-center gap-1.5">
                        <Tag className="w-3.5 h-3.5 text-emerald-500" /> Distinct Keywords ({activeVar.distinctKeywords.length})
                      </span>
                      <button
                        type="button"
                        onClick={() => copyText(activeVar.distinctKeywords.join(', '), 'Keywords')}
                        className="text-xs font-mono text-emerald-600 dark:text-emerald-400 hover:underline cursor-pointer"
                      >
                        Copy Tags
                      </button>
                    </div>
                    <div className="flex flex-wrap gap-1 max-h-24 overflow-y-auto scrollbar-none">
                      {activeVar.distinctKeywords.map((kw, i) => (
                        <span
                          key={i}
                          className={`text-[10.5px] px-2 py-0.5 rounded-lg border ${
                            isLight ? 'bg-neutral-50 border-neutral-200 text-neutral-700' : 'bg-neutral-900 border-neutral-800 text-neutral-300'
                          }`}
                        >
                          {kw}
                        </span>
                      ))}
                    </div>
                  </div>
                </div>

                {/* Negative Prompt & Anti-Similarity Audit Note */}
                <div className={`p-4 rounded-2xl border space-y-1.5 ${
                  isLight ? 'bg-emerald-50/50 border-emerald-200/70 text-emerald-950' : 'bg-emerald-500/10 border-emerald-500/20 text-emerald-200'
                }`}>
                  <div className="text-xs font-bold flex items-center gap-1.5">
                    <ShieldCheck className="w-4 h-4 text-emerald-500" />
                    <span>Adobe Stock Distinct Submission Audit:</span>
                  </div>
                  <p className="text-xs leading-relaxed opacity-90">
                    {activeVar.differentiationNote}
                  </p>
                </div>
              </div>
            );
          })()}

          {/* High-RPM In-Feed Native Google Monetized Unit */}
          <div className="w-full my-4">
            <GoogleAdSenseBanner
              format="in-feed"
              themeMode={themeMode}
              onOpenMonetizeHub={onOpenMonetizeHub}
            />
          </div>
        </div>
      )}

      {/* ADOBE STOCK DISTINCT GUIDELINES MODAL */}
      <AnimatePresence>
        {showGuidelinesModal && (
          <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/80 backdrop-blur-sm">
            <motion.div
              initial={{ scale: 0.95, opacity: 0 }}
              animate={{ scale: 1, opacity: 1 }}
              exit={{ scale: 0.95, opacity: 0 }}
              className={`max-w-2xl w-full p-6 sm:p-8 rounded-[32px] border space-y-5 ${
                isLight ? 'bg-white border-neutral-200 text-neutral-900' : 'bg-[#0e1117] border-neutral-800 text-white'
              }`}
            >
              <div className="flex items-center justify-between pb-3 border-b border-neutral-200 dark:border-neutral-800">
                <div className="flex items-center gap-2">
                  <ShieldCheck className="w-5 h-5 text-emerald-500" />
                  <h3 className="text-lg font-bold">Adobe Stock Distinct Content Guidelines</h3>
                </div>
                <button
                  type="button"
                  onClick={() => setShowGuidelinesModal(false)}
                  className="text-xs font-mono p-1 text-neutral-400 hover:text-neutral-700 dark:hover:text-white cursor-pointer"
                >
                  ✕ Close
                </button>
              </div>

              <div className="space-y-4 text-xs leading-relaxed max-h-[60vh] overflow-y-auto pr-2">
                <div className="p-3.5 rounded-xl bg-amber-500/10 border border-amber-500/20 text-amber-600 dark:text-amber-300">
                  <strong>Official Policy Update (Jun 11, 2026):</strong> "Similar content is one of the top reasons we refuse content submitted to Adobe Stock. When there are too many similar submissions, it reduces visibility to customers."
                </div>

                <div className="space-y-2">
                  <h4 className="font-bold text-sm">Refusal Reasons for Similar Content:</h4>
                  <ul className="list-disc pl-5 space-y-1.5 text-neutral-500 dark:text-neutral-300">
                    <li><strong>Subject &amp; composition:</strong> Same subject photographed/rendered from slightly different angles or distances.</li>
                    <li><strong>Creative treatment:</strong> Identical concepts executed with minor color/filter/lighting changes.</li>
                    <li><strong>Series submissions:</strong> Sequential shots with minimal meaningful difference.</li>
                    <li><strong>Metadata patterns:</strong> Different images tagged with identical titles and keywords.</li>
                  </ul>
                </div>

                <div className="space-y-2">
                  <h4 className="font-bold text-sm">How to Guarantee 90%+ Acceptance:</h4>
                  <ul className="list-disc pl-5 space-y-1.5 text-neutral-500 dark:text-neutral-300">
                    <li>Generate separate visual archetypes (e.g. 1 wide angle banner, 1 macro detail, 1 flat lay knolling).</li>
                    <li>Ensure every submission has a unique title and distinct top 10 keywords.</li>
                    <li>Always check "Created with Generative AI" when uploading.</li>
                  </ul>
                </div>
              </div>

              <button
                type="button"
                onClick={() => setShowGuidelinesModal(false)}
                className="w-full py-2.5 rounded-xl text-xs font-bold bg-neutral-950 text-white dark:bg-white dark:text-black cursor-pointer"
              >
                Understood · Back to Prompt Studio
              </button>
            </motion.div>
          </div>
        )}
      </AnimatePresence>
    </motion.div>
  );
};
